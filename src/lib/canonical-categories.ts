/**
 * 片库的大分类与类型（题材）定义。
 *
 * 采集站的分类表千差万别（有的写「电视剧」、有的写「连续剧」「国产剧」，
 * 有的直接把「短剧」塞进电视剧里），所以这里用**关键词匹配**把各源分类
 * 归并到固定的几个大分类，短剧单独成类、并从电视剧里排除。
 *
 * 前后端共用：前端渲染固定标签，后端按同一套规则挑 type_id。
 */

export interface CanonicalCategory {
  name: string;
  /** 源站分类名包含其中任一关键词即归入该大类 */
  match: string[];
  /** 命中这些关键词时排除（例如「短剧」不能再算电视剧） */
  exclude?: string[];
}

